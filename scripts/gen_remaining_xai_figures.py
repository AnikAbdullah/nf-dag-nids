    tpr = df["DetectionRate_TPR"].values

    colours = ["#b2182b" if t < 0.50 else
               "#fdae61" if t < 0.80 else
               "#1a9850" for t in tpr]
    bars = ax.barh(y, tpr, color=colours, linewidth=0, height=0.7)
    for bar, t, n in zip(bars, tpr, df["AttackCount"]):
        ax.text(min(t + 0.012, 1.005),
                bar.get_y() + bar.get_height() / 2,
                f"{t:.3f}  (n={int(n):,})",
                va="center", fontsize=6.5)

    ax.set_yticks(y)
    ax.set_yticklabels(df["Attack"], fontsize=7)
    ax.set_xlim(0, 1.18)
    ax.set_xlabel("Detection rate (TPR)")
    ax.axvline(0.90, color="grey", linestyle=":", linewidth=0.7)
