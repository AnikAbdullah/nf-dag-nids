# 3.  Adversarial stability bar chart (Lipschitz under Slack-2020 attack)
# ════════════════════════════════════════════════════════════════════════════

def fig_adversarial_stability():
    print("[3] Adversarial stability bar chart")
    df = pd.read_csv(ART / "module_x4_adversarial_stability.csv")

    short = {
        "A1 vanilla KernelSHAP (Slack 2020 baseline)": "A1\nvanilla\nKernelSHAP",
        "A2 Causal Shapley over NF-DAG-v1 (Ng 2025)": "A2\nCausal\nShapley",
        "A4 full pipeline (Causal Shapley + concept)": "A4\nFull",
        "A5 random DAG (negative control)": "A5\nRandom\nDAG",
    }
    df["label"] = df["method"].map(short)
    df["colour"] = [PAL["vanilla"], PAL["causal"], PAL["concept"], PAL["random"]]

    fig, ax = plt.subplots(figsize=(3.6, 3.0))
    x = np.arange(len(df))
    bars = ax.bar(x, df["lipschitz_mean"], yerr=df["lipschitz_std"],
                  color=df["colour"], capsize=3, linewidth=0,
                  error_kw={"linewidth": 0.7, "ecolor": "#333"})
    for bar, m in zip(bars, df["lipschitz_mean"]):
        ax.text(bar.get_x() + bar.get_width() / 2,
                bar.get_height() + 0.02, f"{m:.3f}",
                ha="center", va="bottom", fontsize=6.5)

    a1 = float(df.loc[df["method"].str.startswith("A1"), "lipschitz_mean"].iloc[0])
    a2 = float(df.loc[df["method"].str.startswith("A2"), "lipschitz_mean"].iloc[0])
    pct = (a1 - a2) / a1 * 100
    ax.annotate(f"−{pct:.0f}%", xy=(1, a2), xytext=(0.5, (a1 + a2) / 2),
                arrowprops=dict(arrowstyle="->", lw=0.7, color="black"),
                fontsize=8, fontweight="bold", ha="center")

    ax.set_xticks(x)
    ax.set_xticklabels(df["label"], fontsize=6.5)
    ax.set_ylabel("Lipschitz constant (lower is more stable)")
    ax.set_title("Explanation stability under Slack-2020 perturbation\n(n=12 attack flows)",
                 fontsize=8, pad=4)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.grid(axis="y", linewidth=0.4, color="grey", alpha=0.4, zorder=0)
    ax.set_axisbelow(True)
    ax.set_ylim(0, max(df["lipschitz_mean"] + df["lipschitz_std"]) * 1.25)

    fig.tight_layout(pad=0.4)
    _save(fig, "fig_adversarial_stability.png")

    _write_tex("fig_adversarial_stability.tex", r"""% Adversarial stability bar chart.
% Place in §5.7 (Adversarial Robustness) — companion to Tab. tab:adversarial_stability.

\begin{figure}[t]
  \centering
  \includegraphics[width=0.85\columnwidth]{fig_adversarial_stability}
  \caption{%
    Explanation stability under the Slack 2020 adversarial perturbation
    benchmark.
    Lipschitz constant is the per-flow change in the top-3 feature
    attribution under $\|\delta\|_2 \leq 0.1$ noise (n=12 attack flows).
    Switching from vanilla KernelSHAP (A1) to Causal Shapley over
    NF-DAG-v1 (A2) lowers the cross-cell mean Lipschitz constant by
    $\sim$23\% (per-cell paired median improvement 29.1\%, 11/12 cells
    improve; Tab.~\ref{tab:adversarial_stability}),
    confirming that conditioning attributions on the causal DAG yields
    more stable explanations under the same perturbation budget.
    The random-DAG negative control (A5) achieves similar stability,
    which is expected --- any conditioning structure smooths
    attributions; what NF-DAG-v1 adds is causal \emph{feasibility}
    (Tab.~\ref{tab:feasibility_ablation}), not stability alone.%
  }
  \label{fig:adv_stability}
\end{figure}
""")


