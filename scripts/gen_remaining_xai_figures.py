"""
Generate the remaining XAI-related figures for the paper.

Produces (under artifacts/):
  fig_concept_activation.png        — Layer C activation heatmap
  fig_adversarial_stability.png     — A1/A2/A4/A5 Lipschitz bar chart
  fig_shap_variants.png             — interventional vs asymmetric vs cc-shapley
  fig_family_detection.png          — per-family TPR bar chart
  fig_cf_pareto.png                 — feasibility vs proximity scatter (A2-A5)
  fig_dag_sensitivity.png           — 500-flow flip/remove/PC rho
  fig_faithfulness_per_family.png   — causal vs vanilla sufficiency
  fig_dag_diagram.tex               — LaTeX block for existing nf_dag_v1.png

And the matching LaTeX figure blocks under artifacts/results_tables/.

Usage:
    python scripts/gen_remaining_xai_figures.py
"""
from __future__ import annotations
import json
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
from matplotlib.colors import Normalize

matplotlib.rcParams.update({
    "font.family": "serif",
    "font.size": 8,
    "axes.labelsize": 8,
    "xtick.labelsize": 7,
    "ytick.labelsize": 7,
    "axes.linewidth": 0.6,
    "xtick.major.width": 0.6,
    "ytick.major.width": 0.6,
})

ROOT     = Path(__file__).resolve().parents[1]
ART      = ROOT / "artifacts"
TEX_DIR  = ART / "results_tables"

# A consistent qualitative palette across all figures.
PAL = {
    "causal":   "#2166ac",   # blue   — causal Shapley / A2 / A4
    "vanilla":  "#d6604d",   # red    — vanilla KernelSHAP / DiCE / A0
    "random":   "#999999",   # grey   — random DAG (negative control)
    "concept":  "#5aae61",   # green  — concept abduction / A4
    "high":     "#b2182b",   # dark red for high values in heatmaps
    "low":      "#f7f7f7",
}


def _save(fig: plt.Figure, name: str) -> Path:
    out = ART / name
    fig.savefig(out, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"  → {out.relative_to(ROOT)}")
    return out


def _write_tex(name: str, body: str) -> Path:
    out = TEX_DIR / name
    out.write_text(body)
    print(f"  → {out.relative_to(ROOT)}")
    return out


